test('A06/A07 · 422 real conserva captura y servidor rechaza verified sin permiso', async ({ page }) => {
  await page.goto(urls.demo + '/patients/new')
  const name = 'Ficticia validación ' + crypto.randomUUID()
  await page.getByLabel('Nombres', { exact: true }).fill(name)
  let first = true
  await page.route('**/api/v2/patients', async route => {
    if (route.request().method() !== 'POST' || !first) return route.continue()
    first = false
    const data = route.request().postDataJSON()
    const response = await route.fetch({ postData: JSON.stringify({ ...data, administrative_profile: { ...data.administrative_profile, nationality: { state: 'known', value: '' } } }) })
    expect(response.status()).toBe(422)
    await route.fulfill({ response })
  })
  await review(page)
  await page.getByRole('button', { name: 'Confirmar registro', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('VALIDATION_ERROR')
  await expect(page.getByLabel('Nombres', { exact: true })).toHaveValue(name)
  await page.getByRole('button', { name: 'Revisar registro', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar registro', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Paciente registrado', exact: true })).toBeVisible()
  const response = await page.request.post(urls.demo + '/api/v2/patients', { headers: { 'X-Dev-Actor': 'admision-demo', 'Idempotency-Key': crypto.randomUUID() }, data: { identity_status: 'verified', given_names: name, birth_date: '1990-01-01', verification: ['full_name', 'birth_date'].map(field => ({ field, source_kind: 'official_document', source_reference: 'Documento ficticio' })) } })
  expect(response.status()).toBe(403)
})

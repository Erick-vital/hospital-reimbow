import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
const urls = JSON.parse(process.env.V2_E2E_URLS!)
const fixture = JSON.parse(process.env.V2_E2E_FIXTURES!)
async function search(page: Page) {
  await page.getByRole('button', { name: 'Buscar coincidencias del borrador' }).click()
  await page.getByLabel('Revisé las coincidencias').check()
}
async function review(page: Page) { await search(page); await page.getByRole('button', { name: 'Revisar registro', exact: true }).click() }

test('A01/A02 · captura directa NFC, razones restauradas y provisional persisten', async ({ page }) => {
  await page.goto(urls.demo + '/patients/new')
  await expect(page.getByLabel('Nombres', { exact: true })).toBeVisible()
  await expect(page.getByLabel(/disponibilidad/)).toHaveCount(0)
  await page.getByLabel('Nombres: razón de ausencia').selectOption('unknown')
  await page.getByLabel('Nombres', { exact: true }).fill('Valor temporal')
  await expect(page.getByLabel('Nombres: razón de ausencia')).toHaveCount(0)
  await page.getByLabel('Nombres', { exact: true }).fill('   ')
  await expect(page.getByLabel('Nombres: razón de ausencia')).toHaveValue('unknown')
  await page.getByLabel('Nombres', { exact: true }).fill('  Ficticia Jose\u0301 ' + crypto.randomUUID() + '  ')
  await page.getByLabel('Fecha de nacimiento', { exact: true }).fill('1990-01-01')
  await page.getByLabel('Primer apellido: razón de ausencia').selectOption('unknown')
  await page.getByLabel('Segundo apellido: razón de ausencia').selectOption('not_applicable')
  await page.getByLabel('Nacionalidad: razón de ausencia').selectOption('unknown')
  await page.getByLabel('Nacionalidad', { exact: true }).fill('Temporal')
  await page.getByLabel('Nacionalidad', { exact: true }).fill('')
  await review(page)
  const summary = page.getByLabel('Resumen de captura')
  await expect(summary).toContainText('Desconocido'); await expect(summary).toContainText('No aplica')
  await expect(summary).toContainText('José')
  await page.getByRole('button', { name: 'Volver al borrador' }).click()
  await expect(page.getByLabel('Nacionalidad: razón de ausencia')).toHaveValue('unknown')
  await page.getByRole('button', { name: 'Revisar registro', exact: true }).click()
  const response = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/api/v2/patients'))
  await page.getByRole('button', { name: 'Confirmar registro', exact: true }).click()
  const result = await (await response).json()
  expect(result.identity_status).toBe('provisional')
  expect(result.given_names).toContain('José'); expect(result.given_names).toBe(result.given_names.trim())
  expect(result.identity_field_states).toEqual({ given_names: 'known', family_name: 'unknown', second_family_name: 'not_applicable', birth_date: 'known' })
  expect(result.administrative_profile.nationality).toEqual({ state: 'unknown', value: null })
})


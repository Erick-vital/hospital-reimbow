import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
const urls = JSON.parse(process.env.V2_E2E_URLS!)
const fixture = JSON.parse(process.env.V2_E2E_FIXTURES!)
const results = (page: Page) => page.getByLabel('Coincidencias')
async function search(page: Page, name: string) {
  await page.getByLabel('Nombre', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
}
async function cleanStorage(page: Page) {
  expect(await page.evaluate(async () => [localStorage.length, sessionStorage.length, (await indexedDB.databases()).length, (await caches.keys()).length, (await navigator.serviceWorker.getRegistrations()).length])).toEqual([0,0,0,0,0])
}

test('R01 · filtros, selección, paginación y resultados coinciden con API', async ({ page }) => {
  await page.goto(urls.demo + '/patients')
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Indica al menos un filtro para buscar.')
  await page.getByLabel('Resultados por página').selectOption('5')
  const response = page.waitForResponse(response => response.url().includes('/api/v2/patients?'))
  await search(page, 'Persona ficticia navegador')
  const body = await (await response).json()
  expect(body.total).toBeGreaterThan(5)
  for (const item of body.items) await expect(results(page).getByRole('link', { name: `Consultar paciente ${item.folio}` })).toBeVisible()
  await expect(results(page).getByRole('link')).toHaveCount(body.items.length)
  const next = page.waitForResponse(response => response.url().includes('offset=5'))
  await page.getByRole('button', { name: 'Siguiente' }).click()
  const nextBody = await (await next).json()
  for (const item of nextBody.items) await expect(results(page).getByRole('link', { name: `Consultar paciente ${item.folio}` })).toBeVisible()
  for (const item of body.items) expect(nextBody.items.some((other: { id: string }) => other.id === item.id)).toBe(false)
  await page.getByRole('button', { name: 'Anterior' }).click()
  await expect(results(page).getByRole('link').first()).toBeVisible()
  await page.getByLabel('Nombre', { exact: true }).fill('')
  await page.getByLabel('Folio de paciente', { exact: true }).fill(fixture.patient_folio)
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(results(page).getByRole('link')).toHaveCount(1)
  await results(page).getByRole('link').click()
  await expect(page).toHaveURL(urls.demo + '/patients/' + fixture.patient_id)
  await expect(page.getByRole('region', { name: 'Paciente del contexto actual' })).toContainText(fixture.patient_folio)
  await cleanStorage(page)
})


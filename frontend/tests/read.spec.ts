test('R03 · búsqueda real atrasada no sustituye la vigente', async ({ page }) => {
  await page.goto(urls.demo + '/patients')
  let release!: () => void
  let captured!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  const received = new Promise<void>(resolve => { captured = resolve })
  await page.route('**/api/v2/patients?**', async route => {
    if (new URL(route.request().url()).searchParams.get('folio') !== fixture.patient_folio) return route.continue()
    const response = await route.fetch()
    captured(); await gate
    try { await route.fulfill({ response }) } catch { /* Contexto de filtros cancelado. */ }
  })
  await page.getByLabel('Folio de paciente', { exact: true }).fill(fixture.patient_folio)
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await received
  await page.getByLabel('Folio de paciente', { exact: true }).fill('')
  await search(page, 'Persona ficticia navegador Beta')
  await expect(results(page).getByRole('link').first()).toBeVisible()
  await expect(results(page)).not.toContainText('Persona ficticia navegador Alfa')
  release(); await page.unrouteAll({ behavior: 'wait' })
  await expect(results(page)).not.toContainText(fixture.patient_folio)
})

